/**
 * Write `src/build-seq.generated.ts` from `DSH_BUILD_NUMBER` (CI run number).
 *
 * The product version stays pinned to the upstream desktop line (2.0.3 …) —
 * our own build counter rides as semver build metadata (`2.0.3+b63`) so
 * client telemetry can distinguish builds and the disclaimer gate re-prompts
 * on every release, without touching the installer's version-based upgrade
 * path. Committed default is 0 (plain version); CI overwrites before build
 * and nothing commits the generated value back.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

// CI-only by design (review P2): a local run would leave a large build seq
// dirty in the working tree for someone to commit by accident.
if (process.env.DSH_BUILD_NUMBER !== undefined && !process.env.CI) {
  throw new Error('make-build-seq: refusing a local DSH_BUILD_NUMBER — the build seq is CI-owned; unset it')
}
const raw = process.env.DSH_BUILD_NUMBER
if (raw !== undefined && (!/^\d+$/u.test(raw) || Number.parseInt(raw, 10) < 1)) {
  throw new Error(`make-build-seq: DSH_BUILD_NUMBER must be a positive integer (got ${JSON.stringify(raw)})`)
}
// Normalized (no leading zeros — a raw "063" would be an ES module syntax
// error once written) and per-workflow scoped (github.run_number counts this
// workflow only; a future packaging workflow gets its own series).
const seq = raw === undefined ? '0' : String(Number.parseInt(raw, 10))
const target = join(root, 'src', 'build-seq.generated.ts')
writeFileSync(target, `// GENERATED by scripts/make-build-seq.mjs — do not edit.\nexport const DSH_BUILD_SEQ = ${seq}\n`)
console.log(`make-build-seq: wrote DSH_BUILD_SEQ=${seq} to src/build-seq.generated.ts`)
