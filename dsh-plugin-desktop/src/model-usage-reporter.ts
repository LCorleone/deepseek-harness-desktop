/**
 * Read the desktop package version the same way the Electron runtime does
 * (`desktopProductVersion`): the package manifest beside the built module.
 */
export function modelUsageClientVersion(moduleUrl: string = import.meta.url): string {
  const value: unknown = JSON.parse(readFileSync(new URL('../package.json', moduleUrl), 'utf8'))
  if (value === null || typeof value !== 'object'
    || typeof (value as { version?: unknown }).version !== 'string') {
    throw new Error('dsh-plugin-desktop: package.json has no product version')
  }
  return (value as { version: string }).version
}

/** Every dependency `apply` can take from its host; tests substitute all. */
export interface ModelUsageReporterOptions {
  readonly policy?: DesktopPolicy | undefined
  readonly dsnBlob?: string | undefined
  readonly gatewayBlob?: string | undefined
  readonly environment?: NodeJS.ProcessEnv | undefined
  readonly moduleUrl?: string | undefined
  readonly clientVersion?: string | undefined
  readonly createWriteBoundary?: ModelUsageWriteBoundaryFactory | undefined
  readonly schedule?: ModelUsageSchedule | undefined
  readonly now?: (() => number) | undefined
  readonly logInfo?: ((message: string) => void) | undefined
  readonly logError?: ((message: string) => void) | undefined
}

/**
 * Wire the reporter. A `usageReport: false` policy (the dev variant) keeps
 * this plugin completely inert: no subscription, no connection, no blob
 * decode. Resolution failures degrade to an offline reporter with one
 * sanitized log line — telemetry must never fail the boot.
 */
export function apply(ctx: Context, options: ModelUsageReporterOptions = {}): void {
  const logError = options.logError ?? ((message: string) => { ctx.logger.error(message) })
  const logInfo = options.logInfo ?? ((message: string) => { ctx.logger.info(message) })

  let policy: DesktopPolicy
  try {
    policy = options.policy ?? readDesktopPolicy()
  } catch (cause) {
    logError(`dsh-plugin-desktop: model usage reporting stays offline (unreadable policy): ${sanitizeUsageReportError(cause)}`)
    return
  }
  if (policy.usageReport !== true) return

  let dsn: UsageReportDbDsn
  try {
    dsn = resolveUsageReportDbDsn(
      options.dsnBlob,
      options.environment ?? process.env,
      options.moduleUrl ?? import.meta.url,
    )
  } catch (cause) {
    logError(`dsh-plugin-desktop: model usage reporting stays offline (invalid destination): ${sanitizeUsageReportError(cause)}`)
    return
  }

  // Managed-gateway base URL attribution. A corrupt gateway blob already
  // failed this build loudly on the launcher's own decode; here it only
  // degrades the base_url column to ''.
  let gatewayBaseUrl: string | undefined
  try {
    gatewayBaseUrl = managedModelGateway(policy, options.gatewayBlob ?? MODEL_GATEWAY_BLOB)?.baseUrl
  } catch {
    gatewayBaseUrl = undefined
  }

  const sink = new ModelUsageSink(
    options.createWriteBoundary ?? createMysql2WriteBoundary,
    dsn,
    { now: options.now, schedule: options.schedule, logInfo, logError },
  )

  // Registered before the subscription so Cordis's reverse-order disposal
  // stops the firehose first and then drains the queue (async disposer —
  // unloading awaits it inside the launcher's shutdown grace).
  ctx.effect(() => () => sink.dispose(), 'dsh-plugin-desktop: model usage report drain')

  ctx.inject(['sessions'], (sessionsCtx) => {
    sessionsCtx.effect(() => {
      const projection = new ModelUsageProjection({
        clientVersion: options.clientVersion ?? modelUsageClientVersion(options.moduleUrl),
        userEmail: () => ctx.desktopRuntime?.ssoAccountEmail ?? '',
        baseUrlFor: provider =>
          provider === COMPANY_LLM_GATEWAY_PROVIDER_ROUTE ? gatewayBaseUrl ?? '' : '',
      })
      const stopEvents = sessionsCtx.on('session/event', (session, event) => {
        const row = projection.sessionEvent(session, event)
        if (row !== undefined) sink.enqueue(row)
      })
      const stopDisposed = sessionsCtx.on('session/disposed', (session) => {
        projection.sessionDisposed(session)
      })
      return () => {
        stopDisposed()
        stopEvents()
      }
    }, 'dsh-plugin-desktop: model usage collection')
  })
}
