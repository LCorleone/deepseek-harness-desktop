/**
 * Real mysql2 boundary. Imported lazily from inside the flush path: a
 * disabled or idle reporter never loads the driver, and the dependency stays
 * off the startup path.
 */
export async function createMysql2WriteBoundary(): Promise<ModelUsageWriteBoundary> {
  const mysql = await import('mysql2/promise')
  return {
    async createConnection(config) {
      const connection = await mysql.createConnection({
        host: config.host,
        port: config.port,
        user: config.user,
        password: config.password,
        database: config.database,
        connectTimeout: config.connectTimeout,
      })
      return {
        query: (sql, values) => connection.query(sql, values as unknown[]),
        end: () => connection.end(),
      }
    },
  }
}

