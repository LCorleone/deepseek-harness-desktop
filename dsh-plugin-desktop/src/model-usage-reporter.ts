/**
 * Bounded in-memory queue with a lazy MySQL connection.
 *
 * Flush triggers: the row threshold on enqueue, the interval timer armed
 * while rows wait, and a final best-effort drain on {@link ModelUsageSink.dispose}
 * (Cordis unload awaits the async disposer, so application shutdown drains
 * within the launcher's shutdown grace). Failed writes keep their rows
 * queued and reconnect with a doubling backoff capped at
 * {@link MODEL_USAGE_RECONNECT_MAX_MS}.
 */
export class ModelUsageSink {
  readonly #createBoundary: ModelUsageWriteBoundaryFactory
  readonly #dsn: UsageReportDbDsn
  readonly #now: () => number
  readonly #schedule: ModelUsageSchedule
  readonly #logInfo: (message: string) => void
  readonly #logError: (message: string) => void

  readonly #queue: ModelUsageRow[] = []
  #flushed = 0
  #dropped = 0
  #errors = 0
  #lastFlushAt: number
  #flushing: Promise<void> | undefined
  #flushAgain = false
  #intervalTimer: (() => void) | undefined
  #retryTimer: (() => void) | undefined
  #retryNotBefore = 0
  #backoffMs = 0
  #connection: ModelUsageConnection | undefined
  #connectionTask: Promise<ModelUsageConnection> | undefined
  #disposed = false
  #disposing = false

  constructor(
    createBoundary: ModelUsageWriteBoundaryFactory,
    dsn: UsageReportDbDsn,
    options: ModelUsageSinkOptions = {},
  ) {
    this.#createBoundary = createBoundary
    this.#dsn = dsn
    this.#now = options.now ?? (() => Date.now())
    this.#schedule = options.schedule ?? ((delayMs, run) => {
      const handle = setTimeout(run, delayMs)
      return () => { clearTimeout(handle) }
    })
    this.#logInfo = options.logInfo ?? (() => {})
    this.#logError = options.logError ?? (() => {})
    this.#lastFlushAt = this.#now()
  }

  /** Counter-only status. */
  stats(): ModelUsageSinkStats {
    return {
      queued: this.#queue.length,
      flushed: this.#flushed,
      dropped: this.#dropped,
      errors: this.#errors,
      connected: this.#connection !== undefined,
    }
  }

  /** Enqueue one row; never blocks and never throws. */
  enqueue(row: ModelUsageRow): void {
    if (this.#disposed) {
      this.#dropped += 1
      return
    }
    // Overflow path 1 of 2 (dual overflow semantics, design P5-2 in
    // dev-log/2026-08-22-company-market-lockdown-plan-v2.md): a full queue
    // at enqueue drops the OLDEST row; the retry path in #runFlush drops
    // from the opposite end instead.
    if (this.#queue.length >= MODEL_USAGE_QUEUE_LIMIT_ROWS) {
      this.#queue.shift()
      this.#dropped += 1
    }
    this.#queue.push(row)
    if (this.#queue.length >= MODEL_USAGE_FLUSH_THRESHOLD_ROWS) {
      void this.#flush('threshold')
    } else {
      this.#armIntervalTimer()
    }
  }

  /** Best-effort final drain plus connection end; idempotent. */
  async dispose(): Promise<void> {
    if (this.#disposed || this.#disposing) return
    this.#disposing = true
    this.#cancelIntervalTimer()
    this.#cancelRetryTimer()
    if (this.#flushing !== undefined) {
      try {
        await this.#flushing
      } catch {
        // The in-flight flush already logged its own sanitized failure.
      }
    }
    try {
      await this.#runFlush('dispose', true)
    } catch {
      // Best effort by contract; counters were already logged.
    }
    this.#disposed = true
    await this.#endConnection()
  }

  async #flush(trigger: string, force: boolean = false): Promise<void> {
    if (this.#flushing !== undefined) {
      this.#flushAgain = true
      return this.#flushing
    }
    const task = this.#runFlush(trigger, force).then(
      () => {
        this.#flushing = undefined
        if (this.#flushAgain) {
          this.#flushAgain = false
          void this.#flush(trigger)
        } else if (!this.#disposed && this.#queue.length > 0) {
          this.#armIntervalTimer()
        }
      },
      (cause: unknown) => {
        this.#flushing = undefined
        this.#errors += 1
        this.#logError(`dsh-plugin-desktop: model usage flush crashed trigger=${trigger} errors=${String(this.#errors)}: ${sanitizeUsageReportError(cause, this.#dsn)}`)
      },
    )
    // The stored task resolves only after the follow-up bookkeeping above.
    this.#flushing = task.then(() => {}, () => {})
    return task
  }

  async #runFlush(trigger: string, force: boolean): Promise<void> {
    this.#cancelIntervalTimer()
    while (this.#queue.length > 0 && !this.#disposed) {
      if (!force && this.#now() < this.#retryNotBefore) return
      // Dequeue before writing: an overflow drop-oldest while the batch is
      // in flight would otherwise shift the queue under the batch's feet and
      // the completion splice could remove rows that were never sent.
      const rows = this.#queue.splice(0, this.#queue.length)
      try {
        const connection = await this.#connectionRef()
        await connection.query(modelUsageInsertSql(rows.length), rows.flatMap(modelUsageRowValues))
      } catch (cause) {
        // Overflow path 2 of 2 (dual overflow semantics, design P5-2 in
        // dev-log/2026-08-22-company-market-lockdown-plan-v2.md): a failed
        // batch goes back to the front intact, and rows beyond the limit
        // are dropped from the TAIL (newest) — the retry batch must stay
        // complete and the queue bounded through retries, so this end is
        // the opposite of enqueue's drop-oldest.
        this.#queue.unshift(...rows)
        while (this.#queue.length > MODEL_USAGE_QUEUE_LIMIT_ROWS) {
          this.#queue.pop()
          this.#dropped += 1
        }
        this.#errors += 1
        await this.#dropConnection()
        this.#scheduleRetry()
        this.#logError(`dsh-plugin-desktop: model usage flush failed trigger=${trigger} rows=${String(rows.length)} queued=${String(this.#queue.length)} flushed=${String(this.#flushed)} dropped=${String(this.#dropped)} errors=${String(this.#errors)} connection=failed: ${sanitizeUsageReportError(cause, this.#dsn)}`)
        return
      }
      this.#flushed += rows.length
      this.#lastFlushAt = this.#now()
      this.#backoffMs = 0
      this.#logInfo(`dsh-plugin-desktop: model usage flush ok trigger=${trigger} rows=${String(rows.length)} queued=${String(this.#queue.length)} flushed=${String(this.#flushed)} dropped=${String(this.#dropped)} errors=${String(this.#errors)} connection=ok`)
    }
  }

  #armIntervalTimer(): void {
    if (this.#intervalTimer !== undefined || this.#retryTimer !== undefined || this.#disposed || this.#disposing) return
    const delay = Math.max(0, MODEL_USAGE_FLUSH_INTERVAL_MS - (this.#now() - this.#lastFlushAt))
    this.#intervalTimer = this.#schedule(delay, () => {
      this.#intervalTimer = undefined
      void this.#flush('interval')
    })
  }

  #scheduleRetry(): void {
    if (this.#disposed || this.#disposing) return
    this.#backoffMs = this.#backoffMs === 0
      ? MODEL_USAGE_RECONNECT_BASE_MS
      : Math.min(MODEL_USAGE_RECONNECT_MAX_MS, this.#backoffMs * 2)
    this.#retryNotBefore = this.#now() + this.#backoffMs
    this.#cancelRetryTimer()
    this.#retryTimer = this.#schedule(this.#backoffMs, () => {
      this.#retryTimer = undefined
      void this.#flush('retry')
    })
  }

  async #connectionRef(): Promise<ModelUsageConnection> {
    if (this.#connection !== undefined) return this.#connection
    if (this.#connectionTask === undefined) {
      this.#connectionTask = (async () => {
        const boundary = await this.#createBoundary()
        return await boundary.createConnection({
          host: this.#dsn.host,
          port: this.#dsn.port,
          user: this.#dsn.user,
          password: this.#dsn.password,
          database: this.#dsn.database,
          connectTimeout: MODEL_USAGE_CONNECT_TIMEOUT_MS,
        })
      })()
    }
    try {
      this.#connection = await this.#connectionTask
    } catch (cause) {
      this.#connectionTask = undefined
      throw cause
    }
    return this.#connection
  }

  async #dropConnection(): Promise<void> {
    const connection = this.#connection
    this.#connection = undefined
    this.#connectionTask = undefined
    if (connection !== undefined) {
      try {
        await connection.end()
      } catch {
        // A broken connection's end failure is not actionable.
      }
    }
  }

  async #endConnection(): Promise<void> {
    const connection = this.#connection
    this.#connection = undefined
    this.#connectionTask = undefined
    if (connection !== undefined) {
      try {
        await connection.end()
      } catch {
        // Best effort by contract.
      }
    }
  }

  #cancelIntervalTimer(): void {
    this.#intervalTimer?.()
    this.#intervalTimer = undefined
  }

  #cancelRetryTimer(): void {
    this.#retryTimer?.()
    this.#retryTimer = undefined
  }
}

