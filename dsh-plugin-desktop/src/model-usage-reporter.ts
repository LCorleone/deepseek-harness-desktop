/** Decoded report-database destination; the password never enters a log. */
export interface UsageReportDbDsn {
  readonly host: string
  readonly port: number
  readonly user: string
  readonly password: string
  readonly database: string
}

/**
 * Fixed XOR key. NOT a secret: it must stay byte-identical to
 * `scripts/make-usage-report-blob.mjs` or the decode fails loudly.
 */
const OBFUSCATION_KEY = 'dsh-desktop-usage-report-obfuscation-key-v1'

function invalidDsn(message: string): Error {
  return new Error(`dsh-plugin-desktop: invalid usage report database blob: ${message}`)
}

const HOST_PATTERN = /^[A-Za-z0-9._-]{1,253}$/u

/** Strictly validate one decoded DSN document (shared by blob and env paths). */
function parseDsnDocument(document: unknown): UsageReportDbDsn {
  if (typeof document !== 'object' || document === null || Array.isArray(document)) {
    throw invalidDsn('the decoded payload must be an object')
  }
  const keys = Object.keys(document).sort()
  if (keys.length !== 5 || keys[0] !== 'database' || keys[1] !== 'host' || keys[2] !== 'password'
    || keys[3] !== 'port' || keys[4] !== 'user') {
    throw invalidDsn('the decoded payload must carry exactly host, port, user, password, and database')
  }
  const { host, port, user, password, database } = document as Record<string, unknown>
  if (typeof host !== 'string' || !HOST_PATTERN.test(host)) {
    throw invalidDsn('host must be a bare hostname or IP literal')
  }
  if (typeof port !== 'number' || !Number.isInteger(port) || port < 1 || port > 65_535) {
    throw invalidDsn('port must be an integer between 1 and 65535')
  }
  if (typeof user !== 'string' || user.length === 0) {
    throw invalidDsn('user must be a non-empty string')
  }
  if (typeof password !== 'string' || password.length === 0) {
    throw invalidDsn('password must be a non-empty string')
  }
  if (typeof database !== 'string' || database.length === 0) {
    throw invalidDsn('database must be a non-empty string')
  }
  return Object.freeze({ host, port, user, password, database })
}

/**
 * Decode and strictly validate one obfuscated report-database blob.
 * @param blob - base64 XOR-obfuscated JSON DSN.
 * @returns the validated destination facts.
 * @throws when the blob is malformed; the message never includes blob content.
 */
export function decodeUsageReportDbBlob(blob: string): UsageReportDbDsn {
  if (typeof blob !== 'string' || blob.length === 0) {
    throw invalidDsn('the blob must be a non-empty string')
  }
  let cipher: Buffer
  try {
    cipher = Buffer.from(blob, 'base64')
  } catch (cause) {
    throw invalidDsn(`base64 decoding failed: ${cause instanceof Error ? cause.message : String(cause)}`)
  }
  const key = Buffer.from(OBFUSCATION_KEY, 'utf8')
  const plain = Buffer.from(cipher)
  for (let index = 0; index < plain.length; index += 1) {
    plain[index] = plain[index]! ^ key[index % key.length]!
  }
  let document: unknown
  try {
    document = JSON.parse(plain.toString('utf8')) as unknown
  } catch {
    throw invalidDsn('the decoded payload is not valid JSON')
  }
  return parseDsnDocument(document)
}

/** Environment names of the unpackaged-only destination overrides. */
export const USAGE_REPORT_DB_ENVIRONMENT = Object.freeze({
  host: 'DSH_REPORT_DB_HOST',
  port: 'DSH_REPORT_DB_PORT',
  user: 'DSH_REPORT_DB_USER',
  password: 'DSH_REPORT_DB_PASSWORD',
  database: 'DSH_REPORT_DB_DATABASE',
})

function environmentValue(environment: NodeJS.ProcessEnv, name: string): string | undefined {
  const value = environment[name]
  if (value === undefined) return undefined
  const trimmed = value.trim()
  return trimmed.length === 0 ? undefined : trimmed
}

/**
 * Resolve the report destination: the embedded blob, plus `DSH_REPORT_DB_*`
 * field overrides honored in unpackaged runs only (the `DSH_SSO_*` pattern —
 * a packaged build always uses the pinned blob).
 * @param blob - obfuscated DSN blob (override for tests).
 * @param environment - environment carrying optional overrides.
 * @param moduleUrl - module URL deciding the packaged-layout check.
 * @returns the validated destination.
 * @throws when the blob or the overridden combination is invalid.
 */
export function resolveUsageReportDbDsn(
  blob: string = USAGE_REPORT_DB_BLOB,
  environment: NodeJS.ProcessEnv = process.env,
  moduleUrl: string = import.meta.url,
): UsageReportDbDsn {
  const dsn = decodeUsageReportDbBlob(blob)
  if (isPackagedApplicationPath(fileUrlToPathSafe(moduleUrl))) return dsn
  const host = environmentValue(environment, USAGE_REPORT_DB_ENVIRONMENT.host)
  const port = environmentValue(environment, USAGE_REPORT_DB_ENVIRONMENT.port)
  const user = environmentValue(environment, USAGE_REPORT_DB_ENVIRONMENT.user)
  const password = environmentValue(environment, USAGE_REPORT_DB_ENVIRONMENT.password)
  const database = environmentValue(environment, USAGE_REPORT_DB_ENVIRONMENT.database)
  if (host === undefined && port === undefined && user === undefined
    && password === undefined && database === undefined) return dsn
  const portNumber = port === undefined ? dsn.port : Number.parseFloat(port)
  return parseDsnDocument({
    host: host ?? dsn.host,
    port: portNumber,
    user: user ?? dsn.user,
    password: password ?? dsn.password,
    database: database ?? dsn.database,
  })
}

function fileUrlToPathSafe(moduleUrl: string): string {
  try {
    // Imported lazily-shaped to keep this module free of a node:url side effect
    // at parse time for bundlers that inline it; the URL case is the only one.
    return new URL(moduleUrl).pathname
  } catch {
    return moduleUrl
  }
}

