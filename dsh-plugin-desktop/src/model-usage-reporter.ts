/**
 * Render one error safe for the log: the DSN's host, host:port, user, and
 * password are replaced before the generic secret masker runs. mysql2
 * failures quote the account and host (`Access denied for user 'u'@'h'`)
 * and connect failures quote `host:port`, so both shapes are stripped.
 * @param error - anything thrown around the write path.
 * @param dsn - the destination whose fragments must not survive.
 * @returns the sanitized message (no stack, no DSN).
 */
export function sanitizeUsageReportError(error: unknown, dsn?: UsageReportDbDsn): string {
  let message = error instanceof Error ? error.message : String(error)
  if (dsn !== undefined) {
    const fragments = [dsn.password, dsn.user, dsn.host, `${dsn.host}:${String(dsn.port)}`]
    for (const fragment of fragments) {
      if (fragment.length === 0) continue
      message = message.replaceAll(fragment, '****')
    }
  }
  return maskSecrets(message)
}

