/**
 * Per-call model usage reporting to the company telemetry database (P5).
 *
 * PRIVACY CONTRACT (design review, 2026-09-01): one row per assistant step
 * carries ONLY token counts, provider/model attribution, and wall-clock
 * timing. No prompt, response, reasoning, tool, or error text is ever read
 * from the message, and the log surface of this module is counters and
 * connection status only. `session_id` is an indirect identifier (it reveals
 * when and how much was sent, never what) and stays in the company database.
 *
 * Composition facts:
 *
 * - The plugin subscribes to `session/event` for `request/header` (the
 *   per-session call-config attribution the assembled message does not
 *   carry), `step/start`/`assistant/chunk` (timing boundaries), and
 *   `assistant/message` (the usage record). Upstream guarantees exactly one
 *   assembled message per step; the `(session_id, turn, step)` in-memory
 *   dedup is defensive only, mirrored by the table's UNIQUE key and
 *   INSERT-only writer.
 * - `total_tokens` is the four disjoint buckets (input + cache read + cache
 *   write + output) exactly like the upstream token meter;
 *   `reasoningTokens` is a SUBSET of `outputTokens` and never enters the
 *   total.
 * - Timing mirrors `sessionStats` projection math: latency is
 *   `step/start → assistant/message`, TTFT is the first non-empty delta
 *   chunk, and tokens/second is output tokens over the decode span. A
 *   boundary whose (turn, step) does not match the assembled message is
 *   rejected exactly like `sessionStats` rejects it — the row survives with
 *   NULL timing instead of inheriting a stale step's clock.
 * - Queueing is bounded (5 000 rows, drop-oldest plus a counter) and flushed
 *   on a double trigger (50 rows or every 10 s). The MySQL connection is
 *   created lazily on the FIRST flush attempt — the module never touches
 *   the network from the startup path, and a disabled policy keeps it fully
 *   unwired (no subscription, no connection, no blob decode).
 * - Credentials: a low-privilege INSERT-only account, shipped as an
 *   XOR+base64 obfuscated blob (`src/usage-report-db-blob.ts`, generated by
 *   `scripts/make-usage-report-blob.mjs`; obfuscation is not encryption).
 *   `DSH_REPORT_DB_*` environment overrides are honored in unpackaged runs
 *   only, exactly like the `DSH_SSO_*` pattern. The DSN never enters any
 *   log line: errors pass through {@link sanitizeUsageReportError} before
 *   the logger sees them.
 *
 * @module dsh-plugin-desktop/model-usage-report
 */

