/**
 * Render the multi-row INSERT IGNORE statement. Idempotency rests on the
 * table's UNIQUE(session_id, turn, step); NULL session ids never collide
 * (SQL UNIQUE semantics), which is the intended multi-row shape for
 * attribution-less events.
 */
export function modelUsageInsertSql(rowCount: number): string {
  if (!Number.isInteger(rowCount) || rowCount < 1) {
    throw new TypeError('dsh-plugin-desktop: model usage insert needs at least one row')
  }
  const columns = MODEL_USAGE_COLUMNS.map(column => `\`${column}\``).join(', ')
  const placeholders = `(${MODEL_USAGE_COLUMNS.map(() => '?').join(', ')})`
  return `INSERT IGNORE INTO \`${MODEL_USAGE_TABLE}\` (${columns}) VALUES `
    + `${placeholders}${`, ${placeholders}`.repeat(rowCount - 1)}`
}

/** Flatten one row into statement parameters (column order). */
export function modelUsageRowValues(row: ModelUsageRow): unknown[] {
  return [
    row.userEmail,
    row.provider,
    row.model,
    row.baseUrl,
    row.inputTokens,
    row.cacheReadTokens,
    row.cacheWriteTokens,
    row.outputTokens,
    row.reasoningTokens,
    row.totalTokens,
    row.tokensPerSecond,
    row.ttftMs,
    row.latencyMs,
    row.sessionId,
    row.turn,
    row.step,
    row.clientVersion,
    row.createdAt,
  ]
}

